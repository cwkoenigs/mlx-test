"""Turn results/benchmarks.jsonl into results/single_node.md and results/benchmarks.md.

    python -m mlx_train.report [--benchmarks results/benchmarks.jsonl]

Speedup is computed against the single-rank run with the same name, global batch and compile
setting (the latest one if several). Rows are the latest run per (name, tag, ranks, backend,
batch, compile) combination.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path


def load_rows(path: Path) -> list[dict]:
    rows = []
    if not path.exists():
        return rows
    for line in path.read_text().splitlines():
        line = line.strip()
        if line:
            rows.append(json.loads(line))
    return rows


def latest_per_key(rows: list[dict], key_fn) -> dict:
    out = {}
    for r in rows:  # file is append-only and chronological
        out[key_fn(r)] = r
    return out


def fmt_mem(bs: list[int]) -> str:
    return " / ".join(f"{b / 2**30:.2f}" for b in bs) + " GiB"


def throughput(r: dict) -> tuple[str, float]:
    unit = r.get("throughput_unit", "tokens")
    return unit, r.get(f"{unit}_per_sec", 0.0)


def build_tables(rows: list[dict]) -> tuple[str, str]:
    mlx_rows = [r for r in rows if r.get("framework", "mlx") == "mlx"]
    torch_rows = [r for r in rows if r.get("framework") == "torch"]
    key = lambda r: (r["name"], r.get("tag", ""), r["ranks"], r["backend"], r["global_batch_size"], r["compile"])
    latest = latest_per_key(mlx_rows, key)
    single = {(r["name"], r["global_batch_size"], r["compile"]): r for r in latest.values() if r["ranks"] == 1}

    # ---- single node ---------------------------------------------------------------------
    s = ["# Single-node results", "", "Generated by `python -m mlx_train.report` from `results/benchmarks.jsonl`.", "",
         "| Run | Params | Global batch | Seq len | Compile | Steps/sec | Throughput | Peak mem | Loss first -> final | Host |",
         "|---|---|---|---|---|---|---|---|---|---|"]
    for r in sorted(latest.values(), key=lambda r: (r["params"], r["global_batch_size"], not r["compile"])):
        if r["ranks"] != 1:
            continue
        unit, tp = throughput(r)
        s.append(f"| {r['name']}{(' (' + r['tag'] + ')') if r.get('tag') else ''} | {r['params'] / 1e6:.1f}M | {r['global_batch_size']} | "
                 f"{r.get('seq_len') or '-'} | {'on' if r['compile'] else 'off'} | {r['steps_per_sec']:.2f} | "
                 f"{tp:,.0f} {unit}/s | {fmt_mem(r['peak_mem_bytes_per_rank'])} | "
                 f"{r['first_loss']:.3f} -> {r['final_loss']:.3f} | {', '.join(r['hosts'])} |")
    # compile speedup
    pairs = {}
    for r in latest.values():
        if r["ranks"] == 1:
            pairs.setdefault((r["name"], r["global_batch_size"]), {})[r["compile"]] = r
    comp = [(k, v) for k, v in pairs.items() if True in v and False in v]
    if comp:
        s += ["", "## mx.compile speedup", "", "| Run | Global batch | Steps/sec (no compile) | Steps/sec (compile) | Speedup |", "|---|---|---|---|---|"]
        for (name, gb), v in sorted(comp):
            s.append(f"| {name} | {gb} | {v[False]['steps_per_sec']:.2f} | {v[True]['steps_per_sec']:.2f} | "
                     f"{v[True]['steps_per_sec'] / v[False]['steps_per_sec']:.2f}x |")
    if torch_rows:
        s += ["", "## PyTorch (MPS) comparison", "", "| Run | Params | Global batch | Steps/sec | Throughput | Peak mem | Loss first -> final |", "|---|---|---|---|---|---|---|"]
        for r in latest_per_key(torch_rows, lambda r: (r["name"], r["global_batch_size"])).values():
            unit, tp = throughput(r)
            s.append(f"| {r['name']} (torch) | {r['params'] / 1e6:.1f}M | {r['global_batch_size']} | {r['steps_per_sec']:.2f} | "
                     f"{tp:,.0f} {unit}/s | {fmt_mem(r['peak_mem_bytes_per_rank'])} | {r['first_loss']:.3f} -> {r['final_loss']:.3f} |")

    # ---- benchmark matrix ----------------------------------------------------------------
    b = ["# Benchmark matrix: 1 node vs 2 nodes", "", "Generated by `python -m mlx_train.report`. Speedup is vs the single-node run with the same model, global batch and compile setting.", "",
         "| Model | Params | Global batch | Setup | Backend | Steps/sec | Throughput | Speedup vs 1 node | Peak mem / node |",
         "|---|---|---|---|---|---|---|---|---|"]
    for r in sorted(latest.values(), key=lambda r: (r["params"], r["global_batch_size"], r["ranks"], r["backend"])):
        unit, tp = throughput(r)
        base = single.get((r["name"], r["global_batch_size"], r["compile"]))
        speed = "1.00x" if r["ranks"] == 1 else (f"{r['steps_per_sec'] / base['steps_per_sec']:.2f}x" if base else "n/a")
        setup = f"{r['ranks']} node{'s' if r['ranks'] > 1 else ''} ({', '.join(r['hosts'])})"
        b.append(f"| {r['name']}{(' (' + r['tag'] + ')') if r.get('tag') else ''} | {r['params'] / 1e6:.1f}M | {r['global_batch_size']} | {setup} | "
                 f"{r['backend'] if r['ranks'] > 1 else '-'} | {r['steps_per_sec']:.2f} | {tp:,.0f} {unit}/s | {speed} | "
                 f"{fmt_mem(r['peak_mem_bytes_per_rank'])} |")
    return "\n".join(s) + "\n", "\n".join(b) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--benchmarks", default="results/benchmarks.jsonl")
    ap.add_argument("--out-dir", default="results")
    args = ap.parse_args()
    rows = load_rows(Path(args.benchmarks))
    if not rows:
        print(f"no rows in {args.benchmarks}; run some training first")
        return
    single, matrix = build_tables(rows)
    out = Path(args.out_dir)
    (out / "single_node.md").write_text(single)
    (out / "benchmarks.md").write_text(matrix)
    print(f"wrote {out / 'single_node.md'} and {out / 'benchmarks.md'} from {len(rows)} runs")


if __name__ == "__main__":
    main()
